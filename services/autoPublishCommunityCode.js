const FINAL_BANNER = '10_final.png';

function requiredFiles() {
    return [...SECTIONS.map(section => section.banner), FINAL_BANNER];
}

async function autoPublishCommunityCode(client) {
    if (fs.existsSync(FLAG_PATH)) {
        console.log('ℹ️ Кодекс v3 уже опубликован — повторная отправка пропущена.');
        return;
    }

    const missing = requiredFiles().filter(file => !fs.existsSync(path.join(ASSET_DIR, file)));
    if (missing.length) {
        console.error(`❌ Кодекс v3: отсутствуют баннеры: ${missing.join(', ')}`);
        return;
    }

    const channel = await client.channels.fetch(CHANNEL_ID).catch(error => {
        console.error('❌ Кодекс v3: ошибка получения канала:', error);
        return null;
    });

    if (!channel?.isTextBased?.() || typeof channel.send !== 'function') {
        console.error(`❌ Кодекс v3: канал ${CHANNEL_ID} недоступен или не является текстовым.`);
        return;
    }

    console.log('⚔️ Кодекс v3: начинаю публикацию в правильном порядке...');

    try {
        for (let index = 0; index < SECTIONS.length; index += 1) {
            const section = SECTIONS[index];
            const bannerPath = path.join(ASSET_DIR, section.banner);

            await channel.send({
                files: [new AttachmentBuilder(bannerPath, { name: section.banner })]
            });
            await wait(DELAY_MS);

            for (const embedData of section.embeds) {
                const embed = new EmbedBuilder()
                    .setColor(COLOR)
                    .setTitle(embedData.title)
                    .setDescription(embedData.description);

                await channel.send({ embeds: [embed] });
                await wait(DELAY_MS);
            }

            console.log(`🖼️ Кодекс v3: раздел ${index + 1}/${SECTIONS.length} опубликован.`);
        }

        const finalPath = path.join(ASSET_DIR, FINAL_BANNER);
        await channel.send({
            files: [new AttachmentBuilder(finalPath, { name: FINAL_BANNER })]
        });
        await wait(DELAY_MS);

        const motto = new EmbedBuilder()
            .setColor(COLOR)
            .setTitle('⚔️ ДЕВИЗ GAME SYNDICATE')
            .setDescription('**Уважение важнее эмоций.**\n**Люди важнее игр.**\n**Репутация важнее побед.**');

        await channel.send({ embeds: [motto] });

        fs.mkdirSync(path.dirname(FLAG_PATH), { recursive: true });
        fs.writeFileSync(FLAG_PATH, new Date().toISOString(), 'utf8');
        console.log(`✅ Кодекс v3 полностью опубликован в канале ${CHANNEL_ID}.`);
    } catch (error) {
        console.error('❌ Кодекс v3: публикация прервана:', error);
    }
}

module.exports = { autoPublishCommunityCode };
